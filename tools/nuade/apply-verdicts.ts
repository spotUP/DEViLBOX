#!/usr/bin/env npx tsx
/**
 * apply-verdicts.ts - turn the comparison batch's rows into the table's measured fields (plan D6, NC-4). Nobody edits
 * those fields by hand: this writes src/engine/nuade/nuadeVerdicts.ts, which nuadeFormats.ts merges into the rows.
 *
 *   npx tsx --tsconfig tsconfig.app.json tools/nuade/apply-verdicts.ts
 *
 * Replace rows: the D8 replace rule (verdictRules.replaceVerdict) over the format's recorded songs; pass -> default
 * nuade, fail -> the row's legacy engine and `heldBecause` = the failing measurements. Rows sharing one preference key
 * (markcooksey / markcooksey_old) move together or not at all. Dual rows: DN-1 (verdictRules.dualDefault) once every
 * song has both numbers; until then only the nuade score is written and the default stays ours.
 * A format with no recorded song gets no verdict (it plays as before), and only the rows of the waves that have started
 * (rollout.ts) are written.
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { NUADE_FORMAT_LIST, type NuadeFormat } from '../../src/engine/nuade/nuadeFormats';
import type { FormatEngineChoice } from '../../src/types/formatEngine';
import { loadResults, type ResultRow, type ResultsFile } from './batch';
import { ROOT } from './nuadeCompare';
import { rolledOutRows } from './rollout';
import { dualDefault, replaceVerdict, mean, type SongMeasure } from './verdictRules';

export interface NuadeVerdict {
  uadeEnvelopeCorrelation: number;
  ownEnvelopeCorrelation?: number | null;
  endAgrees: boolean;
  defaultEngine: FormatEngineChoice;
  heldBecause?: string;
  /** Dual rows: why our engine has no score (so DN-1 cannot move the default off ours). */
  ownNote?: string;
}

const round = (x: number): number => Math.round(x * 10000) / 10000;

function ownNoteFor(f: NuadeFormat, recs: ResultRow[]): string {
  const errs = Array.from(new Set(recs.map((r) => r.ownError).filter(Boolean)));
  const bad = recs.find((r) => r.error);
  if (bad) return `not comparable: ${bad.error}`;
  if (recs.length > 0 && recs.every((r) => r.ownRefused)) return `our engine refuses every corpus song by design (${errs.join('; ')}): none is a form it plays`;
  if (recs.some((r) => r.own === undefined)) return 'our engine not measured yet';
  if (errs.length) return `our engine could not be rendered headless: ${errs.join('; ')}`;
  if (recs.some((r) => r.own === null)) return `no headless render of ${f.label}'s own engine (it is not driven through the shared worklet protocol)`;
  return 'our engine not measured';
}

/** The verdicts the recorded rows give, by format id. Pure over the results file and the table. */
export function computeVerdicts(file: ResultsFile, rows: readonly NuadeFormat[] = NUADE_FORMAT_LIST): Record<string, NuadeVerdict> {
  const out: Record<string, NuadeVerdict> = {};
  const measured = (f: NuadeFormat): ResultRow[] => f.corpus.flatMap((song) => file.rows.filter((r) => r.format === f.id && r.song === song));

  const decided: Record<string, { pass: boolean; v: ReturnType<typeof replaceVerdict> }> = {};
  for (const f of rows) {
    const recs = measured(f);
    if (recs.length === 0 || recs.length !== f.corpus.length) continue;
    if (f.role === 'replace') {
      const v = replaceVerdict({ songs: recs });
      decided[f.id] = { pass: v.pass, v };
    } else {
      const good = recs.filter((r) => !r.error && Number.isFinite(r.correlation));
      const m = good.length ? mean(good.map((r) => r.correlation)) : null;
      const dd = dualDefault(recs as SongMeasure[]);
      out[f.id] = {
        uadeEnvelopeCorrelation: round(m ?? 0),
        ...(dd ? { ownEnvelopeCorrelation: round(dd.ownMean) } : {}),
        endAgrees: recs.every((r) => replaceVerdict({ songs: [r] }).endAgrees === true),
        defaultEngine: dd?.defaultEngine === 'nuade' ? 'nuade' : f.legacyEngine,
        ...(dd ? {} : { ownNote: ownNoteFor(f, recs) }),
      };
    }
  }
  // Rows of one preference key move together: every row of the key needs a passing verdict.
  for (const f of rows.filter((r) => r.role === 'replace')) {
    const d = decided[f.id];
    if (!d) continue;
    const siblings = rows.filter((r) => r.prefKey === f.prefKey);
    const blocked = siblings.find((s) => s.id !== f.id && !decided[s.id]?.pass);
    const pass = d.pass && !blocked;
    out[f.id] = {
      uadeEnvelopeCorrelation: round(d.v.meanCorrelation ?? 0),
      endAgrees: d.v.endAgrees ?? false,
      defaultEngine: pass ? 'nuade' : f.legacyEngine,
      ...(pass ? {} : { heldBecause: d.v.heldBecause || `sibling ${blocked?.id} is ${decided[blocked?.id ?? '']?.pass === false ? 'held' : 'not measured'}` }),
    };
  }
  return out;
}

export function render(verdicts: Record<string, NuadeVerdict>): string {
  const body = Object.keys(verdicts).sort().map((id) => `  ${id}: ${JSON.stringify(verdicts[id])},`).join('\n');
  return `/**
 * GENERATED by tools/nuade/apply-verdicts.ts from tools/nuade/nuade-compare.json. Do not edit by hand: change the
 * measurement or the rule (tools/nuade/verdictRules.ts) and run the tool again.
 */
import type { FormatEngineChoice } from '@/types/formatEngine';

export interface NuadeVerdict {
  /** nuade against UADE, mean over the row's corpus songs (20 ms envelope, best lag). */
  uadeEnvelopeCorrelation: number;
  /** Dual rows: our engine against UADE on the same songs. */
  ownEnvelopeCorrelation?: number | null;
  endAgrees: boolean;
  defaultEngine: FormatEngineChoice;
  /** The failing measurements of a replace row that stays on UADE. */
  heldBecause?: string;
  /** Dual rows: why our engine has no score. */
  ownNote?: string;
}

export const NUADE_VERDICTS: Readonly<Record<string, NuadeVerdict>> = {
${body}
};
`;
}

if (process.argv[1]?.endsWith('apply-verdicts.ts')) {
  const file = loadResults(join(ROOT, 'tools/nuade/nuade-compare.json'));
  const v = computeVerdicts(file, rolledOutRows());
  writeFileSync(join(ROOT, 'src/engine/nuade/nuadeVerdicts.ts'), render(v));
  const nu = Object.values(v).filter((x) => x.defaultEngine === 'nuade').length;
  console.log(`${Object.keys(v).length} verdicts written, ${nu} on nuade, ${Object.values(v).filter((x) => x.heldBecause).length} held`);
}
