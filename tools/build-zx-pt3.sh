#!/bin/sh
# Builds public/zx/pt3player.bin + pt3player.json (PT3 player for the ZX Spectrum 128) from public/zx/pt3player.asm.
# Needs sjasmplus. Queue it: ~/.claude/bin/buildq --purpose "..." -- tools/build-zx-pt3.sh
set -eu
ROOT=$(cd "$(dirname "$0")/.." && pwd)
W=$(mktemp -d)
trap 'rm -rf "$W"' EXIT
cd "$ROOT/public/zx"
sjasmplus --nologo --msg=err --raw="$W/p.bin" --sym="$W/p.sym" pt3player.asm
cp "$W/p.bin" pt3player.bin
python3 - "$W/p.sym" pt3player.bin pt3player.json <<'PY'
import json, os, re, sys
sym = {}
for line in open(sys.argv[1]):
    m = re.match(r'^(\w+):\s+EQU\s+0x([0-9A-Fa-f]+)', line)
    if m: sym[m.group(1)] = int(m.group(2), 16)
load = 0x8000
json.dump({'loadAddress': load, 'entry': load, 'size': os.path.getsize(sys.argv[2]), 'bankOffset': sym['BANK'] - load,
           'dataAddress': 0xC000, 'bankSize': 16384, 'usableBanks': [0, 1, 3, 4, 6, 7], 'setupAddress': sym['START'] + 10,
           'vars': sym['VARS'], 'varsEnd': sym['VARSEND']}, open(sys.argv[3], 'w'), indent=1)
PY
# AY-file variant (no boot, no screen, module at 0x9000) for pt3-wasm's PT3 -> .ay wrapper that aylet plays.
sjasmplus --nologo --msg=err -DAYFILE --raw="$W/a.bin" --sym="$W/a.sym" pt3player.asm
python3 - "$W/a.sym" "$W/a.bin" "$ROOT/pt3-wasm/src/pt3_ay_player.h" <<'PY'
import re, sys
sym = {}
for line in open(sys.argv[1]):
    m = re.match(r'^(\w+):\s+EQU\s+0x([0-9A-Fa-f]+)', line)
    if m: sym[m.group(1)] = int(m.group(2), 16)
b = open(sys.argv[2], 'rb').read()
assert sym['VARSEND'] <= sym['MDLADDR'], ('player vars run into the module', hex(sym['VARSEND']))
with open(sys.argv[3], 'w') as f:
    f.write('// Generated by tools/build-zx-pt3.sh from public/zx/pt3player.asm (-DAYFILE). Do not edit.\n#pragma once\n#include <cstdint>\n')
    f.write('constexpr uint16_t kPt3AyLoad = 0x8000, kPt3AyStart = 0x%04X, kPt3AyModule = 0x%04X, kPt3AyVarsEnd = 0x%04X;\n' % (sym['START'], sym['MDLADDR'], sym['VARSEND']))
    f.write('constexpr uint8_t kPt3AyPlayer[%d] = {' % len(b) + ','.join(str(x) for x in b) + '};\n')
print('ay player', len(b), 'bytes, START', hex(sym['START']), 'VARSEND', hex(sym['VARSEND']))
PY
