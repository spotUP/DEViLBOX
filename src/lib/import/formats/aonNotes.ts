export const AON_NOTE_COUNT = 60;

/** Grid note per file note 1..60, derived from the replayer's own tuning-0 period for each. */
const GRID_NOTE_OF_AON: readonly number[] = AON_PERIODS[0].map((p) => periodToGridNote(p));

/** File note byte (1..60; 0 or above 60 is no note) to grid note. */
export function aonNoteToGridNote(aonNote: number): number {
  if (aonNote < 1 || aonNote > AON_NOTE_COUNT) return 0;
  return GRID_NOTE_OF_AON[aonNote - 1];
}

/** Grid note to file note byte (0 when the note is outside the 60 the format holds). */
export function gridNoteToAonNote(gridNote: number): number {
  if (!gridNote) return 0;
  const i = GRID_NOTE_OF_AON.indexOf(gridNote);
  return i < 0 ? 0 : i + 1;
}
