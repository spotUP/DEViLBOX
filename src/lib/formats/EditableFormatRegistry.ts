// src/lib/formats/EditableFormatRegistry.ts
/**
 * EditableFormatRegistry — the single source of truth for "what can DEViLBOX do
 * with this format": edit its patterns, edit its synth voices, export it natively.
 *
 * Historically these facts were scattered across SIX hand-maintained places
 * (research 2026-07-07 §4.1):
 *   - `uadePatternLayout.formatId` on the song (which codec is wired)
 *   - `SynthRegistry` (which synth voices exist)
 *   - `EDITABLE_FORMAT_LABELS` + `NATIVE_EXPORTABLE_LABELS` hand-lists in
 *     `FormatCapabilities.ts` (~90% overlapping)
 *   - the `LAYOUT_EXPORTERS` dispatch map in `nativeExportRouter.ts`
 *
 * A descriptor here co-locates all of it, keyed by the same `formatId` the
 * encoders/exporters already use. Capabilities are then DERIVED:
 *   - a registered pattern codec (or synth voice) ⇒ the format is editable
 *   - a registered exporter (or a chip-RAM pattern codec) ⇒ it is natively
 *     exportable
 *
 * `FormatCapabilities.getFormatCapabilities` consults this registry first and
 * keeps only the genuine special cases the registry cannot yet express as
 * shrunken hand-lists (see the comments there). `nativeExportRouter` reads its
 * `layoutFormatId → {module, fn, ext}` dispatch map straight from the `exporter`
 * descriptors flagged `byLayout` — one map, no duplicate literal.
 *
 * Registration is a side effect of importing `./EditableFormatRegistry.builtins`
 * (mirrors the `SynthRegistry` builtins barrel), so every consumer that imports
 * the accessors below must also import the builtins barrel to populate the map.
 */

import type { TrackerSong } from '@engine/TrackerReplayer';
import type { SynthType } from '@typedefs/instrument';

// ── Descriptor ────────────────────────────────────────────────────────────────

export interface EditableExporterRef {
  /** Module file under `src/lib/export/` (no extension). */
  module: string;
  /** Named export in that module. */
  fn: string;
  /** Extension for exporters that return raw bytes; omit for self-naming results. */
  ext?: string;
  /** Whether this exporter writes companion/sidecar files (e.g. Cinter `.raw`). */
  companions?: boolean;
  /**
   * `true` when the export is dispatched purely on `uadePatternLayout.formatId`
   * (the former `LAYOUT_EXPORTERS` map). These feed `getLayoutExporters()` for
   * the router. Named-format branches (dispatched on `song.format`) omit this.
   */
  byLayout?: boolean;
}

export interface EditableSynthRef {
  /** SynthRegistry descriptor id (e.g. 'SonixSynth'). */
  synthType: string;
  /** Controls component name (e.g. 'SonixControls'). */
  controls: string;
}

export interface EditableFormatDescriptor {
  /** Matches the `layoutFormatId` used by exporters/encoders. */
  formatId: string;
  /**
   * The exact FormatRegistry label this format surfaces as. Used to derive
   * capabilities by label in `getFormatCapabilities`. When a format's real
   * label is intentionally NOT surfaced with a capability yet (preserving
   * historical behavior), leave `label` empty so the descriptor is inert for
   * capability derivation while still serving the router via `formatId`.
   */
  label: string;
  /** Present when a pattern codec (encoder) is registered for this formatId. */
  patternCodec?: { kind: 'fixed' | 'variable' };
  /** Present when a dedicated native exporter exists. */
  exporter?: EditableExporterRef;
  /** Present when a SynthRegistry voice backs this format's instruments. */
  synth?: EditableSynthRef;
  /** Real fixture paths under `public/data/songs/` for the round-trip harnesses. */
  fixtures?: string[];
  /**
   * Present when File > New Song can start a blank song in this format. The
   * template is a blank native file (no notes) that loads through openSong like
   * any dropped file, so the new song gets this format's editor, replayer and
   * native export. Generated by tools/make-new-song-templates.test.ts.
   */
  newSong?: EditableNewSongRef;
  /**
   * Instrument kinds this format can hold. While a song of this format is
   * loaded, every other SynthType is refused on every creation path.
   * Undefined = unlocked (format not classified yet, or generic project).
   */
  instruments?: EditableInstrumentSet;
}

export interface EditableInstrumentSet {
  allowed: SynthType[];
}

export interface EditableNewSongRef {
  /** Path under `public/`, e.g. `templates/monotone.mon`. Its extension is what format detection sees. */
  template: string;
  /** Full English name for the wizard when `label` is empty or not a readable name. */
  name?: string;
}

export interface NewSongFormat {
  formatId: string;
  /** Wizard label: `newSong.name`, else the FormatRegistry label. */
  name: string;
  template: string;
}

// ── Registry ──────────────────────────────────────────────────────────────────

const registry = new Map<string, EditableFormatDescriptor>();

/** Register (or overwrite) a descriptor keyed by its `formatId`. */
export function registerEditableFormat(d: EditableFormatDescriptor): void {
  registry.set(d.formatId, d);
}

/** Set the allowed instrument kinds of a registered descriptor (builtins fill this). */
export function setFormatInstruments(formatId: string, allowed: SynthType[]): void {
  const d = registry.get(formatId);
  if (!d) throw new Error(`[EditableFormatRegistry] setFormatInstruments: unknown formatId ${formatId}`);
  d.instruments = { allowed };
}

/** Allowed SynthTypes for a format, or null when the format is unlocked / unknown / generic. */
export function allowedSynthTypes(formatId: string | null | undefined): readonly SynthType[] | null {
  if (!formatId) return null;
  return registry.get(formatId)?.instruments?.allowed ?? null;
}

/** True when the format (null = generic project) can hold this synth type. */
export function isSynthAllowed(formatId: string | null | undefined, synthType: SynthType): boolean {
  const allowed = allowedSynthTypes(formatId);
  return allowed === null || allowed.includes(synthType);
}

/** Display name of a format for messages (wizard name, else label, else id). */
export function formatDisplayName(formatId: string): string {
  const d = registry.get(formatId);
  return d?.newSong?.name || d?.label || formatId;
}

/** Get the descriptor for a formatId, or undefined. */
export function getEditableFormat(formatId: string): EditableFormatDescriptor | undefined {
  return registry.get(formatId);
}

/** The layout formatId a parsed song carries: the key of its descriptor and of the native export dispatch. */
export function songLayoutFormatId(song: Pick<TrackerSong, 'uadePatternLayout' | 'uadeVariableLayout'>): string {
  return song.uadePatternLayout?.formatId || song.uadeVariableLayout?.formatId || '';
}

/**
 * Formats whose parser sets no layout: the song carries its module in a field
 * of its own, and the native export router dispatches on that field.
 */
type CarrierSong = Pick<TrackerSong, 'format' | 'actionamicsFileData' | 'activisionProFileData' | 'fredReplayerFileData'>;
const CARRIER_FORMAT_IDS: ReadonlyArray<readonly [formatId: string, carries: (song: CarrierSong) => boolean]> = [
  ['fredEditor', (song) => !!song.fredReplayerFileData],
  ['actionamics', (song) => (song.format as string) === 'AST' && !!song.actionamicsFileData],
  ['activisionPro', (song) => (song.format as string) === 'AVP' && !!song.activisionProFileData],
];

/** The editable formatId of a parsed song: its layout formatId, else the format its module carrier names. */
export function songFormatId(song: Pick<TrackerSong, 'uadePatternLayout' | 'uadeVariableLayout'> & CarrierSong): string {
  return songLayoutFormatId(song) || (CARRIER_FORMAT_IDS.find(([, carries]) => carries(song))?.[0] ?? '');
}

/**
 * Formats whose parsed song carries neither a layout nor a carrier id, but
 * does carry an engine field the format store receives (applyEditorMode).
 * Kept apart from songFormatId: that one drives native export dispatch.
 */
type EngineFieldSong = { format?: string; bdFileData?: unknown; sawteethFileData?: unknown };
const ENGINE_FIELD_FORMAT_IDS: ReadonlyArray<readonly [formatId: string, carries: (song: EngineFieldSong) => boolean]> = [
  ['benDaglish', (song) => !!song.bdFileData],
  ['sawteeth', (song) => !!song.sawteethFileData],
  ['monotone', (song) => song.format === 'MON'],
];

/** The formatId whose instrument set locks the editor when this song loads, or '' for an unlocked project. */
export function lockFormatId(song: Omit<Parameters<typeof songFormatId>[0], 'format'> & EngineFieldSong & { format?: string }): string {
  return songFormatId(song as Parameters<typeof songFormatId>[0]) || (ENGINE_FIELD_FORMAT_IDS.find(([, carries]) => carries(song))?.[0] ?? '');
}

/**
 * Did a complete parser produce this song? True when its format has a native
 * exporter: the product edits that format and writes it back, so its parser
 * reads the whole file. Zero notes from such a parser is an empty song (a New
 * Song template), not a stub parser's placeholder grid.
 */
export function parsedByExportableFormat(song: Parameters<typeof songFormatId>[0]): boolean {
  return !!getEditableFormat(songFormatId(song))?.exporter;
}

/** List every registered descriptor (insertion order). */
export function listEditableFormats(): EditableFormatDescriptor[] {
  return Array.from(registry.values());
}

/** Every format a new song can start in, sorted by name (the wizard's Formats group and MCP `new_song`). */
export function listNewSongFormats(): NewSongFormat[] {
  const out: NewSongFormat[] = [];
  for (const d of registry.values()) {
    if (!d.newSong) continue;
    out.push({ formatId: d.formatId, name: d.newSong.name ?? d.label, template: d.newSong.template });
  }
  return out.sort((a, b) => a.name.localeCompare(b.name));
}

// ── Derived capability views (consumed by FormatCapabilities) ──────────────────

/**
 * Set of FormatRegistry labels the registry marks EDITABLE: any descriptor with
 * a pattern codec or a synth voice. Inert (empty-label) descriptors are skipped.
 */
export function getRegistryEditableLabels(): Set<string> {
  const out = new Set<string>();
  for (const d of registry.values()) {
    if (d.label && (d.patternCodec || d.synth)) out.add(d.label);
  }
  return out;
}

/**
 * Set of FormatRegistry labels the registry marks NATIVELY EXPORTABLE: any
 * descriptor with a dedicated exporter OR a chip-RAM pattern codec (which
 * exports via chip-RAM readback). Inert (empty-label) descriptors are skipped.
 */
export function getRegistryExportableLabels(): Set<string> {
  const out = new Set<string>();
  for (const d of registry.values()) {
    if (d.label && (d.exporter || d.patternCodec)) out.add(d.label);
  }
  return out;
}

// ── Router view (consumed by nativeExportRouter) ───────────────────────────────

export interface LayoutExporterEntry {
  module: string;
  fn: string;
  ext?: string;
}

/**
 * The `layoutFormatId → {module, fn, ext}` dispatch map for the native export
 * router — every descriptor whose exporter is flagged `byLayout`. Single source;
 * replaces the former duplicated `LAYOUT_EXPORTERS` literal.
 */
export function getLayoutExporters(): Record<string, LayoutExporterEntry> {
  const out: Record<string, LayoutExporterEntry> = {};
  for (const d of registry.values()) {
    if (d.exporter?.byLayout) {
      out[d.formatId] = { module: d.exporter.module, fn: d.exporter.fn, ext: d.exporter.ext };
    }
  }
  return out;
}
